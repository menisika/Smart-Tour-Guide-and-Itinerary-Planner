/** The Russian form of a noun after a number. @param {number} n @param {[string, string, string]} forms one, few, many */
const plural = (n, [one, few, many]) => {
  const tens = n % 100;
  const units = n % 10;
  if (tens >= 11 && tens <= 14) return many;
  if (units === 1) return one;
  if (units >= 2 && units <= 4) return few;
  return many;
};

