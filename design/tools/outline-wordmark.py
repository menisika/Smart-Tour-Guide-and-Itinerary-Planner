"""Draws the letters of the wordmark as outlines.

    ~/.venvs/claude/bin/python design/tools/outline-wordmark.py

Reads Unbounded (SIL Open Font License 1.1) from design/assets/fonts, sets it
at weight 700, and writes design/system/mark/outline.json: for every letter of
the word its outline as an SVG path and its advance, in units of the font.
design/system/mark.js sets the word from that file, so the wordmark does not
depend on a font being loaded. It needs fontTools and brotli, and is run again
only if the word or the typeface changes.
"""

import json
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

WORD = "Promenade"
WEIGHT = 700
ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "assets/fonts/unbounded/unbounded-latin-wght-normal.woff2"
TARGET = ROOT / "system/mark/outline.json"

font = instantiateVariableFont(TTFont(FONT), {"wght": WEIGHT})
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
metrics = font["hmtx"]

letters = []
for character in WORD:
    name = cmap[ord(character)]
    pen = SVGPathPen(glyphs, ntos=lambda value: str(round(value)))
    # A font's y axis points up; an SVG's points down.
    glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))
    letters.append({"letter": character, "d": pen.getCommands(), "advance": metrics[name][0]})

TARGET.parent.mkdir(parents=True, exist_ok=True)
TARGET.write_text(
    json.dumps(
        {
            "about": "Generated by design/tools/outline-wordmark.py from Unbounded at weight "
            f"{WEIGHT} (SIL Open Font License 1.1). Outlines are in units of the font, y down.",
            "word": WORD,
            "unitsPerEm": font["head"].unitsPerEm,
            "capHeight": font["OS/2"].sCapHeight,
            "letters": letters,
        },
        ensure_ascii=False,
        indent=2,
    )
    + "\n"
)
print(f"wrote {TARGET}: {len(letters)} letters")
